def step_compile(cx):
    cx.run('compile', [sys.executable, 'build_opt.py', 'main', str(cx.jobs)], env=build_env(cx))
    dll = os.path.join(cx.work, cx.game)
    say('  %s %.0f MB; objects %.0f MB' % (cx.game, os.path.getsize(dll) / 1048576.0, disk_mb(os.path.join(cx.work, 'obj_eh_o1'))))


def copy_opus(cx):
    src = cx.tools.get('opus')
    if not src:
        say('  WARNING: no libopus: the game\'s Opus sounds will be silent (deps step above)')
        return ''
    name = os.path.basename(src) if os.path.basename(src).lower() in ('opus.dll', 'libopus-0.dll') else 'opus.dll'
    if os.path.normcase(os.path.abspath(src)) != os.path.normcase(os.path.join(cx.work, name)):
        shutil.copy2(src, os.path.join(cx.work, name))
    return name


def link_linux(cx):
    """The glslang shim (the Vulkan renderer's GLSL -> SPIR-V), the exe linked against the game library, the system's SDL3
    or the one install_deps.sh built (deps/sdl3-linux) beside them (the exe looks in its own folder first: rpath $ORIGIN)."""
    cx.run('link', [cx.tools['clang'], '-O2', '-shared', '-fPIC', 'vk_glslang_shim.c', '-o', 'ssbu_glslang.so'] + cx.tools.get('glslang_libs', GLSLANG_LIBS[0]))
    cx.run('link', [sys.executable, 'build.py', 'link'], env=dict(build_env(cx), RECOMP_EXE=LINUX_EXE))
    lib = os.path.join(REPO, 'deps', 'sdl3-linux', 'lib')
    for n in (os.listdir(lib) if os.path.isdir(lib) else []):
        if n.startswith('libSDL3.so.'):
            shutil.copy2(os.path.join(lib, n), os.path.join(cx.work, n), follow_symlinks=True)
    for f in (LINUX_EXE, 'ssbu_glslang.so', LINUX_GAME):
        if not os.path.exists(os.path.join(cx.work, f)):
            raise Fail('%s was not produced' % f)
    say('  %s %.1f MB, ssbu_glslang.so, %s %.0f MB beside it' % (LINUX_EXE, os.path.getsize(os.path.join(cx.work, LINUX_EXE)) / 1048576.0,
                                                                 LINUX_GAME, os.path.getsize(os.path.join(cx.work, LINUX_GAME)) / 1048576.0))


def step_link(cx):
    cx.state.setdefault('done', {}).pop('prepare', None)       # a new exe: its shaders are prepared again (prepare_shaders)
    if cx.linux:
        return link_linux(cx)
    if cx.runtime_dir:                        # the prebuilt runtime: copied and checked; only the game DLL is linked here
        cx.run('link', [sys.executable, 'build.py', 'gamedll'], env=build_env(cx))
        with open(os.path.join(cx.runtime_dir, 'manifest.json')) as f:
            files = json.load(f)['files']
        for name in files:
            if name.lower().endswith(('.exe', '.dll')):
                dst = os.path.join(cx.work, name)
                if os.path.exists(dst + '.old'):              # what a running launcher left last time
                    try:
                        os.remove(dst + '.old')
                    except OSError:
                        pass
                if os.path.exists(dst) and sha256_file(dst) == files[name]['sha256']:
                    continue                                  # already this one (the launcher that runs this install, its SDL3.dll)
                try:
                    shutil.copy2(os.path.join(cx.runtime_dir, name), dst)
                except PermissionError:                       # in use (the launcher runs the install): a running file can be renamed
                    os.replace(dst, dst + '.old')
                    shutil.copy2(os.path.join(cx.runtime_dir, name), dst)
                if sha256_file(dst) != files[name]['sha256']:
                    raise Fail('%s does not match the runtime package after copying' % name)
        how = 'from the runtime package'
    else:
        cx.run('link', [sys.executable, 'build.py', 'link'], env=dict(build_env(cx), RECOMP_EXE=EXE))
        build_launcher(cx)
        how = 'built here'
    for f in (EXE, 'SDL3.dll', GAME_DLL):
        if not os.path.exists(os.path.join(cx.work, f)):
            raise Fail('%s was not produced' % f)
    launcher_game(cx)
    if os.path.exists(os.path.join(cx.work, 'title-logo.png')):    # exes copied again (a new package): the logo's icon back in
        import launcher_art
        try:
            launcher_art.make_icon(cx.work)
            launcher_art.stamp_icon(cx.work)
        except ImportError:                                         # no Pillow: no icon
            pass
    opus = copy_opus(cx)
    ff = copy_ffmpeg(cx)
    say('  %s, SDL3.dll%s %s%s; %s %.0f MB linked here%s' % (
        EXE, ', ' + LAUNCHER if os.path.exists(os.path.join(cx.work, LAUNCHER)) else '', how, ', ' + opus if opus else '',
        GAME_DLL, os.path.getsize(os.path.join(cx.work, GAME_DLL)) / 1048576.0, '; FFmpeg %d DLLs' % ff if ff else ''))


def launcher_game(cx):
    """build/config/launcher.ini game = the folder of the dump this build is made from, when it is not <build>/dump (the
    launcher's default): a dump folder of the player's own is used where it is, and the launcher asked for it again."""
    game = os.path.dirname(cx.state['dump']['romfs'])
    ini = os.path.join(cx.build, 'config', 'launcher.ini')
    if os.path.normcase(game) == os.path.normcase(os.path.join(cx.build, 'dump')) and not os.path.exists(ini):
        return
    lines = []
    if os.path.exists(ini):
        with open(ini, encoding='utf-8', errors='replace') as f:
            lines = [l for l in f.read().splitlines() if l.split('=', 1)[0].strip().lower() != 'game']
    os.makedirs(os.path.dirname(ini), exist_ok=True)
    with open(ini, 'w', encoding='utf-8', newline='\r\n') as f:
        f.write('\n'.join(['game = ' + game] + lines) + '\n')


def build_launcher(cx):
    """TomodachiLauncher.exe and bntx_png.exe (the launcher's logo) when the exe is built here; scripts/make_release.py ships
    them in the runtime package. Optional: without the launcher the game still starts (scripts/run.py)."""
    clang = cx.tools.get('launcher_clang') or cx.tools['clang']
    sdl = cx.tools['sdl3']
    obj = os.path.join(cx.work, 'obj_launcher')
    os.makedirs(obj, exist_ok=True)
    try:
        cx.run('link', [clang, '-x', 'c++', '-std=c++17', '-O2', '-w', '-D_CRT_SECURE_NO_WARNINGS', '-DLAUNCHER_VERSION="%s"' % version(),
                        '-I' + os.path.join(REPO, 'launcher'), '-I' + os.path.join(REPO, 'third_party', 'stb'),
                        '-I' + os.path.join(sdl, 'include'), '-c', os.path.join(REPO, 'launcher', 'launcher.cpp'), '-o', os.path.join(obj, 'launcher.o')],
               log='launcher')
        cx.run('link', [clang, os.path.join(obj, 'launcher.o'), os.path.join(sdl, 'lib', 'x64', 'SDL3.lib'), '-luser32', '-lshell32', '-lole32',
                        '-lgdi32', '-ladvapi32', '-Wl,/SUBSYSTEM:WINDOWS', '-Wl,/ENTRY:mainCRTStartup', '-o', os.path.join(cx.work, LAUNCHER)], log='launcher')
    except Fail as e:
        say('  WARNING: the launcher was not built (it needs a clang with C++17 for the MSVC library: LAUNCHER_LLVM or '
            'C:\\Program Files\\LLVM): %s' % str(e).splitlines()[0])
    try:
        cx.run('link', [cx.tools['clang'], '-O2', '-w', '-D_CRT_SECURE_NO_WARNINGS', os.path.join(REPO, 'tools', 'extract', 'bntx_png.c'),
                        os.path.join(REPO, 'runtime', 'tex_decode.c'), '-I' + os.path.join(REPO, 'runtime'), '-o', os.path.join(cx.work, BNTX_PNG)],
               log='launcher')
    except Fail as e:
        say('  WARNING: %s was not built: %s' % (BNTX_PNG, str(e).splitlines()[0]))


def version():
    """The port's version: version.txt at the repository root (one line)."""
    try:
        with open(os.path.join(REPO, 'version.txt')) as f:
            return f.read().strip() or 'dev'
    except OSError:
        return 'dev'


def step_prepare(cx):
    """Every shader container of the game, taken out of its files into build/cache/shader_store, then compiled for this
    PC's graphics card (prepare_shaders), so neither the first start nor play waits for them. And the launcher's logo,
    from the game's own files."""
    d = cx.state['dump']
    game = os.path.dirname(d['romfs'])
    cx.run('prepare', [sys.executable, os.path.join(REPO, 'scripts', 'shader_store.py'), game, cx.build, os.path.join(cx.bin, 'main.elf')], cwd=REPO)
    say('  shader store: %s' % os.path.join(cx.build, 'cache', 'shader_store'))
    if cx.linux:                              # Vulkan: every stage of the store translated to SPIR-V now (no window, no GPU needed)
        cx.run('prepare', [sys.executable, os.path.join(REPO, 'scripts', 'launcher_art.py'), game, cx.build, '--fonts'], cwd=REPO)
        t0 = time.time()
        out = cx.run('prepare', ['./' + LINUX_EXE, '--prepare-shaders', '../cache/shader_store'], log='prepare_shaders')
        say('  shaders: %s (%s)' % (next((l.strip() for l in reversed(out.splitlines()) if l.strip()), 'prepared'), fmt(time.time() - t0)))
        return
    try:
        cx.run('prepare', [sys.executable, os.path.join(REPO, 'scripts', 'launcher_art.py'), game, cx.build], cwd=REPO)
        say('  launcher logo and icon: %s' % os.path.join(cx.work, 'title-logo.png'))
    except Fail as e:                         # the launcher then writes the name in text
        say('  WARNING: the launcher\'s logo could not be made: %s' % str(e).splitlines()[0])
    try:
        prepare_shaders(cx)
    except Exception as e:                    # the game then prepares them at its first start, as before
        say('  WARNING: the shaders could not be prepared now (%s): the game prepares them at its first start' % str(e).splitlines()[0])


def prepare_shaders(cx):
    """Every shader of the store compiled for this PC's graphics driver now, by the game itself (TOMO_PREPARE_ONLY:
    runtime/boot.c prepares and quits without starting the game), so its first start has nothing left to prepare. Before,
    a first start sat on "preparing shaders" for 12 minutes on a fast PC, longer on others, and players took it for a hang
    (issues #10, #14, #19). It runs as tomodachi_play.exe, the launcher's copy of the exe: the driver's cache and ours are
    kept per exe name, and the copy keeps the exe's time, as the launcher's CopyFile does, so the start finds them ready."""
    exe, play = os.path.join(cx.work, EXE), os.path.join(cx.work, 'tomodachi_play.exe')
    main_elf = os.path.join(cx.bin, 'main.elf')
    if not (os.path.isfile(exe) and os.path.isfile(main_elf)):
        say('  shaders: not prepared now (no game exe or main.elf yet): the game prepares them at its first start')
        return
    shutil.copy2(exe, play)
    env = {k: v for k, v in os.environ.items() if not k.startswith(('RECOMP_', 'SSBU_', 'TOMO_'))}
    env.update(SSBU_ROMFS=cx.state['dump']['romfs'], SSBU_USERDATA=os.path.join(cx.build, 'userdata'),
               SSBU_SHOW='0', SSBU_VOLUME='0', TOMO_PREPARE_ONLY='1')
    os.makedirs(env['SSBU_USERDATA'], exist_ok=True)
    say('  shaders: compiling every shader of the game for your graphics card now (10-30 minutes, once), so the game starts quickly')
    # OpenGL on NVIDIA cards, Vulkan on the others (the exe's own choice): Vulkan's stages are translated first, on all processors, without the GPU
    r = subprocess.run([play, '--renderer'], cwd=cx.work, env=env, capture_output=True, text=True, errors='replace')
    if r.returncode == 0 and r.stdout.strip().splitlines()[-1:] == ['vk']:
        out = cx.run('prepare', [play, '--prepare-shaders', '../cache/shader_store'], log='prepare_shaders')
        say('  shaders: %s' % next((l.strip() for l in reversed(out.splitlines()) if l.strip()), 'translated'))
    os.makedirs(cx.logs, exist_ok=True)
    t0, last = time.time(), 0.0
    moved = [time.time(), '']                 # the last time the "N of M ready" count changed, and that line
    with open(os.path.join(cx.logs, 'prepare_shaders.log'), 'ab') as f:
        p = subprocess.Popen([play, main_elf], cwd=cx.work, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)

        def watchdog():                       # a driver that stops answering must not hold the installer: the game prepares at its start
            while p.poll() is None:
                if time.time() - moved[0] > 900:
                    p.kill()
                    return
                time.sleep(5)
        threading.Thread(target=watchdog, daemon=True).start()
        for line in p.stdout:
            f.write(line)
            s = line.decode('utf-8', 'replace').strip()
            if s.startswith('shaders: '):
                count = s.split(' ready')[0]
                if count != moved[1]:
                    moved[0], moved[1] = time.time(), count
                if time.time() - last >= 30 or 'prepared' in s:
                    say('  ' + s)
                    last = time.time()
        rc = p.wait()
    if rc:
        raise Fail('the game\'s shader preparation ended with exit %d after %s (see logs\\prepare_shaders.log)' % (rc, fmt(time.time() - t0)))
    say('  shaders: ready (%s)' % fmt(time.time() - t0))


RUNNERS = {'deps': step_deps, 'stage': step_stage, 'convert': step_convert, 'tables': step_tables, 'lift': step_lift,
           'sdk': step_sdk, 'compile': step_compile, 'link': step_link, 'prepare': step_prepare}
ALWAYS = {'deps', 'stage'}               # cheap, and they fill the in-memory context


def how_to_run(cx):
    say('')
    if cx.linux:
        say('Start the game: ./play.sh   (scripts/linux/install_desktop.sh adds it to your application menu)')
        return
    say('Start the game: %s in %s (or the "Tomodachi Life" shortcut the installer makes).' % (LAUNCHER, cx.work))
    say('The shaders are compiled: the game starts in seconds (after a graphics driver update it prepares them once more).')
    say('Without the launcher:  python scripts/run.py')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--target', choices=('windows', 'linux'), default='windows', help='linux: a native Linux build in <repo>/build-linux')
    ap.add_argument('--dump', help='folder with exefs\\ and romfs\\ (and optionally sysdata\\) dumped from your console')
    ap.add_argument('--exefs'), ap.add_argument('--romfs'), ap.add_argument('--sysdata')
    ap.add_argument('--build', help='build folder (default: the install location of build_location.txt, else <repo>/build)')
    ap.add_argument('--jobs', type=int, help='parallel compiler jobs (default min(24, cpus, one per 1.75 GB of RAM))')
    ap.add_argument('--llvm', help='LLVM 9.0.0 folder (bin\\clang.exe)')
    ap.add_argument('--sdl3', help='SDL3 development package (VC) folder: include\\, lib\\x64\\')
    ap.add_argument('--vulkan-headers', help='Khronos Vulkan-Headers folder (include\\vulkan\\)')
    ap.add_argument('--glslang', help=argparse.SUPPRESS)       # not used by this game (OpenGL); accepted for older command lines
    ap.add_argument('--suyu', help='source checkout of a yuzu-family emulator (only src\\core\\hle\\service\\mii is read)')
    ap.add_argument('--opus', help='libopus DLL (opus.dll or libopus-0.dll) or the folder holding it (optional)')
    ap.add_argument('--imgui', help='Dear ImGui v1.91.9b source folder (imgui.h, imgui.cpp): the in-game settings menu (optional)')
    ap.add_argument('--sdk-roots', help='another list of SDK functions to lift (default: tools/lifter/sdklift_roots.txt)')
    ap.add_argument('--runtime', help='prebuilt runtime package (zip or folder, scripts/make_release.py): the exe is not built here, '
                                      'and neither MSVC, the Windows SDK, SDL3, Vulkan-Headers nor suyu is needed')
    ap.add_argument('--runtime-any-tree', action='store_true', help='use a runtime package made from another version of the sources')
    ap.add_argument('--nocrt', action='store_true', help='build the game library with LLVM alone (the exe is still built here)')
    ap.add_argument('--redo', help='repeat this step')
    ap.add_argument('--from', dest='from_step', help='repeat this step and all after it')
    ap.add_argument('--only', help='run only this step')
    ap.add_argument('--dry-run', action='store_true', help='check the tools and the dump (step deps), then list what would run')
    ap.add_argument('--status', action='store_true'), ap.add_argument('--steps', action='store_true'), ap.add_argument('--run', action='store_true')
    a = ap.parse_args()
    if a.steps:
        say(' '.join(STEPS))
        return 0
    cx = Ctx(a)
    if a.status:
        for s in STEPS:
            r = cx.state.get('done', {}).get(s)
            say('%-8s %s' % (s, ('done  %s' % fmt(r['secs'])) if r else '-'))
        return 0
    if a.run:
        how_to_run(cx)
        return 0
    todo = STEPS
    done = cx.state.setdefault('done', {})
    force = set()
    for opt in (a.redo, a.from_step, a.only):
        if opt and opt not in STEPS:
            say('unknown step %s (steps: %s)' % (opt, ' '.join(STEPS)))
            return 2
    if a.redo:
        force.add(a.redo)
    if a.from_step:
        force |= set(STEPS[STEPS.index(a.from_step):])
    if a.only:
        todo = sorted({'deps', 'stage', a.only}, key=STEPS.index)
        force.add(a.only)
    # a finished build whose game files have gone since (an antivirus quarantines the 250 MB unsigned game DLL, or a
    # copy was interrupted): compile (the objects are kept, so only the DLL is linked again) and link run again
    if 'link' in done and not a.dry_run:
        gone = [f for f in ((LINUX_EXE, LINUX_GAME) if cx.linux else (EXE, GAME_DLL, 'SDL3.dll')) if not os.path.exists(os.path.join(cx.work, f))]
        if gone:
            say('%s missing from %s although the build was finished (an antivirus may have removed it: Windows Security > '
                'Protection history): it is made again' % (', '.join(gone), cx.work))
            for s in ('compile', 'link'):
                done.pop(s, None)
    t_all = time.time()
    for i, s in enumerate(STEPS):
        if s not in todo:
            continue
        if s in done and s not in force and s not in ALWAYS:
            say('[%d/%d] %s: done earlier (%s), skipped' % (i + 1, len(STEPS), s, fmt(done[s]['secs'])))
            continue
        if a.dry_run and s != 'deps':
            say('[%d/%d] %s: would run' % (i + 1, len(STEPS), s))
            continue
        say('[%d/%d] %s ...' % (i + 1, len(STEPS), s))
        t0 = time.time()
        try:
            RUNNERS[s](cx)
        except Fail as e:
            say('FAILED at step %s: %s' % (s, e))
            say('fix the problem and run the same command again: finished steps are skipped.')
            cx.save()
            return 1
        secs = time.time() - t0
        if s not in ALWAYS or s not in done:
            done[s] = {'secs': secs, 'at': time.strftime('%Y-%m-%d %H:%M')}
        cx.save()
        say('[%d/%d] %s: ok  %s' % (i + 1, len(STEPS), s, fmt(secs)))
    say('')
    say('all steps finished in %s; build folder %.0f MB' % (fmt(time.time() - t_all), disk_mb(cx.build)))
    how_to_run(cx)
    return 0


if __name__ == '__main__':
    sys.exit(main())
