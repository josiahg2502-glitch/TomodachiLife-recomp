"""Partial re-lift, compile and link of the game for an instruction patch list (recomp.py PATCHES; N3).

    python recomp_partial.py <patch file> <tag> [--jobs=N] [--lift-only]

    e.g.  python recomp_partial.py patches\\kinds.txt n3     ->  gen_n3\\, obj_n3\\, ssbu_game_n3.dll (+ .lib)
          RECOMP_DLL=ssbu_game_n3.dll RECOMP_OBJ=obj_n3 RECOMP_EXE=ssbu_n3k.exe python build.py link

Nothing of the default build is touched: gen_eh_o2\\, obj_eh_o1\\ and ssbu_game_eh_o1.dll are only read.
  1 lift     every generated file (48 KB of guest code each) that holds a patched address is lifted twice with
             recomp_eh's own function: WITHOUT the patches it must reproduce the file in gen_eh_o2 byte for byte
             (proof that this is the same lifter and the same function list), WITH them it goes to gen_<tag>\\.
             The number of changed lines per file is printed: it must be the number of patches in it.
  2 compile  build_opt's compiler call (same flags and fallback ladder) -> obj_<tag>\\
  3 link     all objects of obj_eh_o1 with the re-compiled ones replaced -> ssbu_game_<tag>.dll
An exe selects the DLL at link time (its import library): see the build.py line above.
"""
import collections
import concurrent.futures
import os
import re
import shutil
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    patch_file, tag = args[0], args[1]
    jobs = int(next((a.split('=')[1] for a in sys.argv if a.startswith('--jobs=')), '14'))
    src_gen, base_obj = os.path.join(HERE, 'gen_eh_o2'), os.path.join(HERE, 'obj_eh_o1')
    gen, obj, dll = os.path.join(HERE, 'gen_' + tag), os.path.join(HERE, 'obj_' + tag), os.path.join(HERE, 'ssbu_game_%s.dll' % tag)
    os.environ.pop('RECOMP_PATCHES', None)
    import recomp
    import recomp_eh
    t0 = time.time()
    patches = recomp.load_patches(patch_file)
    env = recomp.Env()
    env.imports = set()
    env.full = True
    _, _, eh_starts = recomp_eh.eh_info()
    env.starts = sorted(set(env.compute_starts()) | set(eh_starts))
    all_funcs = sorted(int(m, 16) for m in re.findall(r'^void f_([0-9a-f]+)\(Ctx \*c\);', open(os.path.join(src_gen, 'funcs.h')).read(), re.M))
    buckets = collections.OrderedDict()
    for a in all_funcs:
        buckets.setdefault((a - recomp.BASE) // recomp.BUCKET, []).append(a)
    # a patched address is lifted in every entry e with (last function start <= address) <= e <= address: the function
    # itself and branch targets inside it that are lifted as entries of their own; each lives in the file of its entry
    import bisect
    need = collections.Counter()
    for a in patches:
        s = env.starts[bisect.bisect_right(env.starts, a) - 1]
        for e in all_funcs[bisect.bisect_left(all_funcs, s):bisect.bisect_right(all_funcs, a)]:
            need[(e - recomp.BASE) // recomp.BUCKET] += 1
    print('%d patches in %d files; function entries %d (%.0fs)' % (len(patches), len(need), len(env.starts), time.time() - t0), flush=True)
    os.makedirs(gen, exist_ok=True)
    os.makedirs(obj, exist_ok=True)
    shutil.copy2(os.path.join(src_gen, 'funcs.h'), os.path.join(gen, 'funcs.h'))

    def lift(entries):
        env.wanted = collections.OrderedDict()
        texts = [recomp_eh.lift_function(env, a)[0] for a in entries]
        return '/* generated by recomp_eh.py -- do not edit */\n#include "runtime.h"\n#include "funcs.h"\n\n' + '\n\n'.join(texts) + '\n'
    names, bad = [], 0
    for b in sorted(need):
        name = 'c_%04x.c' % b
        recomp.PATCHES = {}
        plain = lift(buckets[b])
        with open(os.path.join(src_gen, name)) as f:
            have = f.read()
        if plain != have:
            print('  %s: the re-lift WITHOUT patches differs from %s: NOT the same lifter / function list, stop' % (name, src_gen))
            bad += 1
            continue
        recomp.PATCHES = patches
        text = lift(buckets[b])
        recomp.PATCHES = {}
        changed = sum(1 for x, y in zip(plain.split('\n'), text.split('\n')) if x != y)
        same_len = len(plain.split('\n')) == len(text.split('\n'))
        print('  %s: identical without patches; with patches %d lines differ (%d patches)%s' % (name, changed, need[b], '' if same_len and changed == need[b] else '   <-- CHECK'), flush=True)
        path = os.path.join(gen, name)
        if not os.path.exists(path) or open(path).read() != text:
            with open(path, 'w') as f:
                f.write(text)
        names.append(name)
    if bad:
        return 1
    print('lift done (%.0fs)' % (time.time() - t0), flush=True)
    if '--lift-only' in sys.argv:
        return 0

    os.environ['RECOMP_GEN'], os.environ['RECOMP_OBJ'], os.environ['RECOMP_DLL'] = 'gen_' + tag, 'obj_' + tag, os.path.basename(dll)
    import build_opt
    def compile_one(name):
        s, o = os.path.join(gen, name), os.path.join(obj, name[:-2] + '.obj')
        if os.path.exists(o) and os.path.getmtime(o) >= os.path.getmtime(s):
            return name, 0, '', 0.0, 'up to date'
        code, out, secs, note = build_opt.compile_file(s, o, ['-w', '-fno-strict-aliasing', '-I', HERE, '-I', gen])
        return name, code, out, secs, note
    t1 = time.time()
    failed = 0
    with concurrent.futures.ThreadPoolExecutor(jobs) as pool:
        for name, code, out, secs, note in pool.map(compile_one, names):
            print('  compiled %s: exit %s %.0fs %s %s' % (name, code, secs, note, out.strip()[-300:] if code else ''), flush=True)
            failed += bool(code)
    print('compile: %d files, %d failed, %.0fs' % (len(names), failed, time.time() - t1), flush=True)
    if failed:
        return 1
    t2 = time.time()
    mine = set(n for n in os.listdir(obj) if n.endswith('.obj'))
    objs = sorted(os.path.join(obj if n in mine else base_obj, n) for n in os.listdir(base_obj) if n.endswith('.obj'))
    rsp = dll + '.rsp'
    with open(rsp, 'w') as f:
        f.write('\n'.join('"%s"' % o.replace('\\', '/') for o in objs))
    shim = os.path.join(HERE, os.environ.get('RECOMP_SHIM', 'game_shim_eh.c'))
    r = subprocess.run([build_opt.build.CLANG, '-shared', '-O1', '-w', '-I', HERE, '-I', src_gen, shim, '@' + rsp, '-o', dll], capture_output=True, text=True, errors='replace')
    print((r.stdout + r.stderr)[-3000:])
    print('link %s: exit %d, %d objects (%d of them re-compiled), %.0f MB, %.0fs' % (os.path.basename(dll), r.returncode, len(objs), len(mine), os.path.getsize(dll) / 1048576.0 if os.path.exists(dll) else 0, time.time() - t2))
    print('total %.0fs' % (time.time() - t0))
    return r.returncode


if __name__ == '__main__':
    sys.exit(main())
